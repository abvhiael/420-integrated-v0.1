package shuffle

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"github.com/consensys/gnark-crypto/ecc"
	"github.com/consensys/gnark/backend/groth16"
	"github.com/consensys/gnark/backend/witness"
	"github.com/consensys/gnark/frontend"
	"github.com/consensys/gnark/frontend/cs/r1cs"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// Re-execute cryptographic verification from committed genuine evidence without
// regenerating valid proof material. Relate every VK to its actual generated
// Solidity verifier, and every proof's ABI bytes to its actual public witness.
func TestWS8CommittedCryptographicEvidence(t *testing.T) {
	root := filepath.Join("fixtures", "ws8")
	type keyRecord struct {
		Name           string `json:"name"`
		RelationSHA256 string `json:"relationSHA256"`
	}
	type proofRecord struct {
		Name string `json:"name"`
		Key  string `json:"key"`
	}
	var manifest struct {
		Keys   []keyRecord   `json:"keys"`
		Proofs []proofRecord `json:"proofs"`
	}
	data, err := os.ReadFile(filepath.Join(root, "manifest.json"))
	if err != nil {
		t.Fatal(err)
	}
	if err = json.Unmarshal(data, &manifest); err != nil {
		t.Fatal(err)
	}
	circuits := map[string]frontend.Circuit{"InitialDeck52": &InitialDeck52{}, "Reencrypt52": &Reencrypt52{},
		"Delivery": &EncryptedShareDeliveryV1{}, "RecipientPoP": &RecipientKeyPossessionV1{},
		"Aggregate": &ThresholdKeyAggregateV1{}, "Partial": &PartialDecryptCircuit{}, "Unmask": &CardUnmaskCircuit{}}
	if len(manifest.Keys) != 7 || len(manifest.Proofs) != 41 {
		t.Fatal("incomplete seven-key/41-proof evidence")
	}
	keys := map[string]groth16.VerifyingKey{}
	for _, record := range manifest.Keys {
		circuit, ok := circuits[record.Name]
		if !ok || keys[record.Name] != nil {
			t.Fatal("unexpected/duplicate circuit")
		}
		cs, err := frontend.Compile(ecc.BN254.ScalarField(), r1cs.NewBuilder, circuit)
		if err != nil {
			t.Fatal(err)
		}
		var relation bytes.Buffer
		if _, err = cs.WriteTo(&relation); err != nil {
			t.Fatal(err)
		}
		digest := sha256.Sum256(relation.Bytes())
		if hex.EncodeToString(digest[:]) != record.RelationSHA256 {
			t.Fatal(record.Name, "compiled relation differs from proving setup")
		}
		vk := groth16.NewVerifyingKey(ecc.BN254)
		raw, err := os.ReadFile(filepath.Join(root, "keys", record.Name+".vk"))
		if err != nil {
			t.Fatal(err)
		}
		if _, err = vk.ReadFrom(bytes.NewReader(raw)); err != nil {
			t.Fatal(err)
		}
		var generated bytes.Buffer
		if err = vk.ExportSolidity(&generated); err != nil {
			t.Fatal(err)
		}
		source, err := os.ReadFile(filepath.Join("..", "..", "..", "contracts", "src", "bet", "generated", "WS8"+record.Name+"Verifier.sol"))
		if err != nil {
			t.Fatal(err)
		}
		expected := strings.Replace(generated.String(), "contract Verifier {", "contract WS8"+record.Name+"Verifier {", 1)
		if strings.ReplaceAll(string(source), "\r\n", "\n") != expected {
			t.Fatal(record.Name, "generated verifier does not match actual VK")
		}
		keys[record.Name] = vk
	}
	seen := map[string]bool{}
	for _, record := range manifest.Proofs {
		if seen[record.Name] || keys[record.Key] == nil {
			t.Fatal("duplicate proof or unknown VK")
		}
		seen[record.Name] = true
		read := func(suffix string) []byte {
			t.Helper()
			b, e := os.ReadFile(filepath.Join(root, "proofs", record.Name+suffix))
			if e != nil {
				t.Fatal(e)
			}
			return b
		}
		proof := groth16.NewProof(ecc.BN254)
		if _, err = proof.ReadFrom(bytes.NewReader(read("Proof.bin"))); err != nil {
			t.Fatal(err)
		}
		public, err := witness.New(ecc.BN254.ScalarField())
		if err != nil {
			t.Fatal(err)
		}
		serialized := read(".public")
		if err = public.UnmarshalBinary(serialized); err != nil {
			t.Fatal(err)
		}
		if err = groth16.Verify(proof, keys[record.Key], public); err != nil {
			t.Fatal(record.Name, err)
		}
		encoded := read(".abi")
		solidity := proof.(interface{ MarshalSolidity() []byte }).MarshalSolidity()
		if len(encoded) < 256 || !bytes.Equal(encoded[:256], solidity) || len(serialized) < len(encoded)-256 ||
			!bytes.Equal(encoded[256:], serialized[len(serialized)-(len(encoded)-256):]) {
			t.Fatal(record.Name, "ABI proof/public mismatch")
		}
		t.Log("verified committed genuine proof", record.Name)
	}
}
