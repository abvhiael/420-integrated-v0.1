import {writeFileSync,readFileSync} from 'node:fs';
import {independentSeven} from '../../clients/420bet-poker/crypto/nlhe-reference.mjs';
import {referenceAward} from '../../clients/420bet-poker/crypto/nlhe-pot-reference.mjs';
let seed=0x420056;
const rnd=n=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed%n;};
const byte=n=>n.toString(16).padStart(2,'0');
let ranks='',pots='';
for(let k=0;k<256;k++){
 const deck=Array.from({length:52},(_,i)=>i);
 for(let i=51;i>0;i--){const j=rnd(i+1);[deck[i],deck[j]]=[deck[j],deck[i]];}
 const cards=deck.slice(0,7),rank=independentSeven(cards);
 let score=rank[0];for(let i=1;i<=5;i++)score=score*15+(rank[i]??0);
 ranks+=cards.map(byte).join('')+score.toString(16).padStart(8,'0');
 const n=2+k%8,c=Array.from({length:9},(_,i)=>i<n?1+rnd(40):0);
 // Keep two equal highest live contributions, so no uncalled excess remains.
 c[0]=40;c[n-1]=40;
 const folded=c.map((_,i)=>i>=n||rnd(3)===0);folded[0]=folded[n-1]=false;
 const ratings=c.map(()=>1+rnd(4)),button=rnd(9);
 const gross=c.reduce((a,b)=>a+b,0),rake=k%3===0?0:rnd(gross+1);
 const paid=referenceAward({contributions:c,folded,ranks:ratings.map(x=>[x]),button,rake});
 pots+=c.map(byte).join('')+folded.map(x=>x?'01':'00').join('')+
  ratings.map(byte).join('')+byte(button)+rake.toString(16).padStart(4,'0')+paid.map(x=>x.toString(16).padStart(4,'0')).join('');
}
let ratios='';
const wide=()=>{let x=0n;for(let i=0;i<8;i++)x=(x<<32n)|BigInt(rnd(0x100000000));return x;};
for(let i=0;i<32;i++){
 const d=wide()||1n,a=wide()%d,n=wide()%d;
 ratios+=[a,n,d,a*n/d].map(x=>x.toString(16).padStart(64,'0')).join('');
}
