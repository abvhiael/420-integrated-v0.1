"""GOV-PRE-08 Step 3: 15 independently witnessed protected BLS validators.

Local qualification only. Keys are generated by the separate, explicit,
insecure fixture provisioner; the *production* certified-producer never sees
key files. Every quorum share crosses its own live fourtwentyd -> mTLS remote
stake-signer -> independent PostgreSQL witnessed durable signing-history path.
There is no process-local key fallback or signature fabrication.
"""
import copy
import hashlib
import json
import os
from pathlib import Path
import queue
import socket
import subprocess
import threading
import time

class Committee:
    def __init__(self, root, directory, genesis, timestamp, launch):
        self.root=Path(root)
        self.private=Path(directory)/"protected-committee"
        self.launch=launch
        self.fixture=self.root/"bin/settlement-fixture"
        self.producer=self.root/"bin/certified-producer"
        self.signer=self.root/"bin/stake-signer"
        self.validator=self.root/"bin/fourtwentyd"
        self.witness=os.environ.get("STAKE_SIGNER_PG_DSN","")
        if not self.witness.startswith("postgresql://signing:") or "sslmode=verify-full" not in self.witness:
            raise AssertionError("independently authenticated TLS signing-witness PostgreSQL is mandatory")
        subprocess.run([str(self.fixture),"--provision-protected-committee",str(self.private),
                        "--genesis",genesis,"--timestamp",timestamp],
                       cwd=self.root,check=True)
        self.trust=self.private/"trust.json"
        self.policies=self.private/"policies.json"
        self.trustdata=json.loads(self.trust.read_text())
        self.public=json.loads(self.policies.read_text())
        assert len(self.public)==15 and len(self.trustdata["Members"])==15
        self.pin=hashlib.sha256(self.trust.read_bytes()).hexdigest()
        self.seed=hashlib.sha256(b"420-step4.5-devnet-seed").hexdigest() # existing LOCAL devnet seed, not a production chain parameter
        self.processes=[]
        self.servers=[]
        self.queues=[]
        self.signing_evidence=[]
        self._setup()

    def _command(self,args,input_bytes=None):
        return subprocess.run(args,cwd=self.root,input=input_bytes,check=True,
                              stdout=subprocess.PIPE,stderr=subprocess.PIPE)
    def _certificates(self):
        tls=self.private/"tls"
        tls.mkdir(mode=0o700)
        ca=tls/"ca"
        self._command(["openssl","req","-x509","-newkey","ec","-pkeyopt",
            "ec_paramgen_curve:P-256","-nodes","-keyout",str(ca)+".key",
            "-out",str(ca)+".pem","-days","1","-subj","/CN=GOV-PRE08-LOCAL-CA"])
        (tls/"ca.key").chmod(0o600)
        def one(seat,role):
            name=f"{seat:02d}-{role}"
            base=tls/name
            self._command(["openssl","req","-new","-newkey","ec","-pkeyopt",
                "ec_paramgen_curve:P-256","-nodes","-keyout",str(base)+".key",
                "-out",str(base)+".csr","-subj","/CN=LOCAL-"+name])
            ext=base.with_suffix(".ext")
            ext.write_text("extendedKeyUsage="+("serverAuth\nsubjectAltName=DNS:localhost,IP:127.0.0.1\n"
                if role=="server" else "clientAuth\n"))
            self._command(["openssl","x509","-req","-in",str(base)+".csr",
                "-CA",str(ca)+".pem","-CAkey",str(ca)+".key","-set_serial",str(100+seat*2+(role=="client")),
                "-out",str(base)+".pem","-days","1","-extfile",str(ext)])
            (tls/(name+".key")).chmod(0o600)
            pub=self._command(["openssl","x509","-in",str(base)+".pem","-pubkey","-noout"]).stdout
            der=self._command(["openssl","pkey","-pubin","-outform","DER"],input_bytes=pub).stdout
            return (str(base)+".pem",str(base)+".key",hashlib.sha256(der).hexdigest())
        self.certificates=[]
        for seat in range(15):
            self.certificates.append((one(seat,"server"),one(seat,"client")))
        return tls

    def _setup(self):
        tls=self._certificates()
        for seat in range(15):
            base=self.private/f"seat-{seat:02d}"
            remote=base/"signer"
            local=base/"validator"
            (remote/"witness.dsn").write_text(self.witness)
            (remote/"witness.dsn").chmod(0o600)
            policy_hash=hashlib.sha256((remote/"policy.json").read_bytes()).hexdigest()
            cert_server,cert_client=self.certificates[seat]
            address=f"127.0.0.1:{18820+seat}"
            arguments=["--policy",str(remote/"policy.json"),"--policy-sha256",policy_hash,
                "--history",str(remote/"history.json"),"--bls-ikm",str(remote/"bls.hex"),
                "--witness-dsn",str(remote/"witness.dsn"),
                "--tls-cert",cert_server[0],"--tls-key",cert_server[1],"--tls-ca",str(tls/"ca.pem"),
                "--client-spki-sha256",cert_client[2],"--listen",address]
            signing_env={k:v for k,v in os.environ.items() if k not in ("STAKE_SIGNER_PG_DSN","PGPASSWORD")}
            signing_env["STAKE_SIGNER_HEALTH_FILE"]=str(remote/"health.json")
            # One-time provision of an *unused* remote BLS identity into its
            # own local history and independent, durable SQL witness row.
            self._command([str(self.signer),*arguments,"--provision-never-used-key"])
            server=self.launch(f"protected-signer-{seat:02d}",[str(self.signer),*arguments],
                               env=signing_env)
            self.servers.append(server)
            until=time.monotonic()+15
            while time.monotonic()<until:
                if server.poll() is not None: raise RuntimeError("protected signer exited: "+str(seat))
                try:
                    with socket.create_connection(("127.0.0.1",18820+seat),timeout=.2):break
                except OSError:time.sleep(.04)
            else:raise RuntimeError("protected signer not ready: "+str(seat))
            signing_env["STAKE_VALIDATOR_HEALTH_FILE"]=str(local/"health.json")
            cmd=[str(self.validator),"--protected-signing","--signer","https://"+address,
                 "--signing-policy",str(local/"policy.json"),
                 "--signing-policy-sha256",policy_hash,
                 "--signing-history",str(local/"history.json"),
                 "--signer-client-cert",cert_client[0],"--signer-client-key",cert_client[1],
                 "--signer-ca",str(tls/"ca.pem"),"--signer-spki-sha256",cert_server[2]]
            proc=self.launch(f"protected-validator-{seat:02d}",cmd,env=signing_env,input_stream=True)
            self.processes.append(proc)
            responses=queue.Queue()
            self.queues.append(responses)
            def receive(stream,q):
                for line in stream:
                    try:q.put(json.loads(line))
                    except ValueError:q.put({"invalidOutput":line})
            threading.Thread(target=receive,args=(proc.stdout,responses),daemon=True).start()
        assert len({p.pid for p in [*self.servers,*self.processes]})==30
        assert all(p.poll() is None for p in [*self.servers,*self.processes])

    def _exec(self,mode,plan,**extra):
        args=[str(self.producer),"--trust",str(self.trust),"--policies",str(self.policies),
              "--rotation-seed",self.seed,"--plan",str(plan),"--mode",mode]
        for key,val in extra.items():args+=["--"+key,str(val)]
        return subprocess.run(args,cwd=self.root,text=True,capture_output=True,timeout=35)

    def batch(self,plan):
        result=self._exec("batch",plan)
        if result.returncode:raise RuntimeError("protected producer batch rejected: "+result.stderr)
        return json.loads(result.stdout)

    def _sign(self,seat,duty):
        proc=self.processes[seat]
        if proc.poll() is not None or self.servers[seat].poll() is not None:
            raise RuntimeError("protected validator/signer stopped before signing: "+str(seat))
        proc.stdin.write(json.dumps(duty,separators=(",",":"))+"\n")
        proc.stdin.flush()
        try:response=self.queues[seat].get(timeout=20)
        except queue.Empty as e:raise RuntimeError("protected validator did not sign: "+str(seat)) from e
        if "Result" not in response or proc.poll() is not None:
            raise RuntimeError("protected validator produced no authentic signed duty: "+str(seat))
        return response

    def certify(self,plan,slot,workdir):
        prepared=self._exec("duties",plan)
        if prepared.returncode:raise RuntimeError("cannot prepare pinned native proposer: "+prepared.stderr)
        d=json.loads(prepared.stdout)
        assert len(d["Votes"])==15 and d["ProposerSeat"] in range(15)
        proposer=self._sign(d["ProposerSeat"],d["Proposal"])
        votes=[self._sign(i,d["Votes"][i]) for i in range(15)]
        assert all(p.poll() is None for p in [*self.servers,*self.processes])
        proposal_path=Path(workdir)/f"protected-proposal-{slot}.json"
        votes_path=Path(workdir)/f"protected-votes-{slot}.json"
        proposal_path.write_text(json.dumps(proposer))
        votes_path.write_text(json.dumps({"Shares":votes}))
        # Exercise fail-closed QC acceptance *without* submitting mutations to
        # execution. Exactly ten authentic seats do not constitute quorum.
        if slot==1:
            def denied(shares,override_proposer=None):
                bad=Path(workdir)/"invalid-protected-votes.json"
                bad.write_text(json.dumps({"Shares":shares}))
                pr=proposal_path
                if override_proposer is not None:
                    pr=Path(workdir)/"invalid-protected-proposer.json"
                    pr.write_text(json.dumps(override_proposer))
                result=self._exec("certify",plan,proposal=pr,votes=bad)
                assert result.returncode!=0 and not result.stdout, "invalid QC/producer proof escaped"
            denied(votes[:10])
            denied(votes[:11]+[votes[1]])
            corrupt=copy.deepcopy(votes)
            corrupt[0]["Result"]["Signature"][0]^=1
            denied(corrupt)
            forged=copy.deepcopy(proposer)
            forged["Proposal"]["Slot"]+=1
            denied(votes,forged)
        result=self._exec("certify",plan,proposal=proposal_path,votes=votes_path)
        if result.returncode:raise RuntimeError("15 independently protected votes could not certify native Geth payload: "+result.stderr)
        record=json.loads(result.stdout)
        bitmap=__import__("base64").b64decode(record["Certificate"]["SignerBitmap"],validate=True)
        assert len(bitmap)==2 and sum(byte.bit_count() for byte in bitmap)==15, "QC must use all fifteen independently protected votes"
        assert record["Certificate"]["Slot"]==slot and len(votes)==15
        self.signing_evidence.append({"slot":slot,"proposerSeat":d["ProposerSeat"],
             "protectedProposer":True,"protectedVotes":len(votes),
             "remoteSignerProcesses":len(self.servers),
             "validatorProcesses":len(self.processes),
             "aggregateVerifiedByProductionCollector":True})
        return record
