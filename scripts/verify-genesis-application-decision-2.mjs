import assert from "node:assert/strict";
import fs from "node:fs";
const read=x=>fs.readFileSync(x,"utf8");
const c=JSON.parse(read("config/genesis-applications.json"));
const d=JSON.parse(read("config/genesis-application-decision-2.json"));
const doc=read("docs/GENESIS-DAPPS.md");
const frozen=["420 Wallet","420 Explorer","420 Search","420 Analytics","420 AppStore","420 Verify","420 Notifications","420 Registry","420 Names","420 Identity","420 Gaming Protocol","420 Arbitration","420 Swap","420 Bridge","420 Stake","420 Governance","420 AI","420 Attention","420 Token","420 Status","420Arcade","420 Faucet"];
assert.equal(d.decision_id,"GENESIS_APPLICATION_DECISION_2");
assert.equal(d.immutable_prior_catalog_entries,22);
assert.equal(c.status,"FROZEN");
assert.equal(c.decision_id,"GENESIS_APPLICATION_DECISION_1");
assert.equal(c.apps.length,51);
assert.deepEqual(c.apps.filter(x=>!d.entries.some(z=>z.name===x.name)).map(x=>x.name),frozen);
assert.equal(new Set(c.apps.map(x=>x.name)).size,51);
assert.equal(new Set(d.entries.map(x=>x.name)).size,29);
assert.equal(d.entries.length,29);
assert.equal(c.apps[50].name,"420 Faucet");
const expected=[...frozen.slice(0,-1),...d.entries.map(e=>e.name),"420 Faucet"];
assert.deepEqual(c.apps.map(a=>a.name),expected);
const groups=Object.values(d.groups).flat();
assert.equal(groups.length,d.entries.length);
assert.deepEqual(groups.slice().sort(),d.entries.map(x=>x.name).sort());
for(const e of d.entries) {
 const app=c.apps.find(a=>a.name===e.name);
 assert.equal(app.class,e.class);
 assert.equal(app.contracts_required,e.contracts_required);
 assert.ok(app.purpose.includes(e.existing_authority),"Lost existing authority dependency for "+e.name);
 assert.equal(e.release_enabled,false);
 assert.ok(["external_only","release_gated","regulated"].includes(e.readiness));
}
for(const n of ["DOOBr","LIFTd","420Bet"])assert.equal(d.entries.find(x=>x.name===n).readiness,"regulated");
for(const n of ["420 Search","420 AppStore"])assert.equal(c.apps.filter(x=>x.name===n).length,1);
const catalogSection=doc.split("## Frozen Genesis catalog\n")[1]?.split("\n420 Governance is")[0];
assert.ok(catalogSection,"Missing published catalog");
const publicLines=catalogSection.split("\n").filter(x=>/^\d+\. /.test(x));
assert.deepEqual(publicLines,c.apps.map((a,i)=>`${i+1}. ${a.name}${a.name==="420 Faucet"?" — testnet only":""}`));
assert.ok(doc.includes("Genesis Application Decision #2"));
assert.ok(d.principles.some(x=>/not deployment/.test(x)));
console.log("Genesis Decision #2 PASS: 51 unique apps; immutable 22-entry baseline; 29 exactly classified additions; 3 regulated disabled; published order and dependencies match.");
